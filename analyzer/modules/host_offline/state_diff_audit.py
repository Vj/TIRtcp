"""
TIRtcp Runtime State-Diff Analyzer
Ingests state_diff.json generated by scripts/dynamic_capture.ps1 to detect:
  1. Dropped binaries/scripts (.exe, .dll, .ps1, .bat, .vbs, .js) in monitored user/app directories
  2. Modified runtime configuration/database files
  3. Newly added or altered HKCU/HKLM Run/RunOnce persistence entries
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

from analyzer.core.compliance_loader import ComplianceMapper
from analyzer.core.schema import (
    Confidence,
    Finding,
    FindingStatus,
    Severity,
)

EXECUTABLE_EXTS = {".exe", ".dll", ".sys", ".ps1", ".bat", ".cmd", ".vbs", ".js", ".hta", ".msi"}


def analyze_state_diff(
    state_diff_path: Path,
    mapper: ComplianceMapper,
) -> List[Finding]:
    """Evaluate pre/post execution filesystem and registry Run-key diffs."""
    findings: List[Finding] = []
    if not state_diff_path.exists():
        return findings

    try:
        diff_data: Dict[str, Any] = json.loads(state_diff_path.read_text(encoding="utf-8"))
    except Exception as exc:
        return [
            Finding(
                check_id="TCP-HOST-001",
                title="Runtime State-Diff JSON Parse Error",
                category="Host & Runtime State Diff",
                status=FindingStatus.TOOLING_GAP,
                severity=Severity.INFO,
                confidence=Confidence.LOW,
                affected_asset=str(state_diff_path),
                summary=f"Failed to parse state_diff.json: {exc}",
            )
        ]

    target_exe = diff_data.get("target_exe", str(state_diff_path))
    created_files: List[str] = diff_data.get("created_files") or []
    modified_files: List[str] = diff_data.get("modified_files") or []
    run_key_changes: Dict[str, str] = diff_data.get("run_key_changes") or {}

    host_refs = mapper.resolve("TCP-HOST-001")
    ipc_refs = mapper.resolve("TCP-IPC-001")

    # 1. Registry Run/RunOnce persistence modifications
    if run_key_changes:
        findings.append(
            Finding(
                check_id="TCP-IPC-001",
                title="Runtime Persistence Added to Windows Run / RunOnce Registry Key",
                category="Host & Runtime State Diff",
                status=FindingStatus.FAIL,
                severity=Severity.HIGH,
                confidence=Confidence.HIGH,
                affected_asset=target_exe,
                summary=(
                    f"Target execution added or modified {len(run_key_changes)} startup persistence "
                    "entry/entries under HKCU/HKLM Run or RunOnce."
                ),
                evidence={"run_key_changes": run_key_changes},
                remediation="Remove unauthorized Run/RunOnce entries and restrict startup registration to signed administrative installers.",
                compliance_support=ipc_refs,
            )
        )

    # 2. Dropped executables/scripts vs. non-executable data files
    dropped_execs = [f for f in created_files if Path(f).suffix.lower() in EXECUTABLE_EXTS]
    dropped_other = [f for f in created_files if Path(f).suffix.lower() not in EXECUTABLE_EXTS]

    if dropped_execs:
        findings.append(
            Finding(
                check_id="TCP-HOST-001",
                title="Executable or Script Dropped to Disk During Runtime Session",
                category="Host & Runtime State Diff",
                status=FindingStatus.FAIL,
                severity=Severity.HIGH,
                confidence=Confidence.HIGH,
                affected_asset=target_exe,
                summary=(
                    f"Application created {len(dropped_execs)} executable/script file(s) during execution; "
                    "if dropped into user-writable AppData/Temp paths, verify signature and origin."
                ),
                evidence={"dropped_executables": dropped_execs[:25]},
                remediation="Avoid dropping unsigned binaries or scripts into user-writable directories at runtime.",
                compliance_support=host_refs,
            )
        )

    if dropped_other or modified_files:
        findings.append(
            Finding(
                check_id="TCP-HOST-001",
                title="Runtime Filesystem Artifacts Created or Modified",
                category="Host & Runtime State Diff",
                status=FindingStatus.OBSERVATION,
                severity=Severity.INFO,
                confidence=Confidence.HIGH,
                affected_asset=target_exe,
                summary=(
                    f"Observed {len(dropped_other)} new non-executable file(s) and {len(modified_files)} "
                    "modified file(s) across monitored install/AppData directories."
                ),
                evidence={
                    "created_files_sample": dropped_other[:25],
                    "modified_files_sample": modified_files[:25],
                },
                compliance_support=host_refs,
            )
        )

    if not findings:
        findings.append(
            Finding(
                check_id="TCP-HOST-001",
                title="Runtime State Diff Clean (No Unexpected Drops or Run-Key Persistence)",
                category="Host & Runtime State Diff",
                status=FindingStatus.VERIFIED_PASS,
                severity=Severity.INFO,
                confidence=Confidence.HIGH,
                affected_asset=target_exe,
                summary="Pre/post execution diff recorded zero dropped binaries or Run-key persistence modifications.",
                evidence={"state_diff_file": state_diff_path.name},
                compliance_support=host_refs,
            )
        )

    return findings
